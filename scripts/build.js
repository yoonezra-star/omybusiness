function renderArticleToc(headings = []) {
  const visibleHeadings = headings
    .filter((heading) => heading.level === "h2" && !/^목차$/i.test(heading.text))
    .slice(0, 8);
  if (!visibleHeadings.length) return "";

  return `<nav class="article-toc" aria-label="글 목차">
    <h2>글 목차</h2>
    <ol>
      ${visibleHeadings.map((heading) => `<li><a href="#${escapeHtml(heading.id)}">${escapeHtml(heading.text)}</a></li>`).join("")}
    </ol>
  </nav>`;
}

function escapeHtml(value = "") {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function absoluteUrl(routePath = "/") {
  return `${site.url}${routePath === "/" ? "" : encodeURI(routePath)}`;
}

function formatDate(dateString) {
  if (!dateString) return "";
  return new Intl.DateTimeFormat("ko-KR", {
    year: "numeric",
    month: "long",
    day: "numeric",
  }).format(new Date(dateString));
}

function routeToFile(routePath) {
  const decoded = decodeURIComponent(routePath.split("?")[0]);
  const segments = decoded.split("/").filter(Boolean);
  return path.join(dist, ...segments, "index.html");
}

async function writeRoute(routePath, html) {
  const file = routeToFile(routePath);
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, html);
}

